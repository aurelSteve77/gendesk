"""Results report.

Renders everything the pipeline produced into a single markdown document, so the
numbers quoted in the README are generated rather than transcribed.
"""

from __future__ import annotations

import json
from pathlib import Path

import numpy as np
import pandas as pd

from gendesk.config import Config
from gendesk.evaluation.ablations import summarise_headline
from gendesk.utils.logging import get_logger
from gendesk.utils.paths import REPORT_DIR, RUN_DIR

log = get_logger(__name__)

HEADLINE_COLUMNS = [
    "strategy",
    "cagr",
    "vol",
    "sharpe",
    "sortino",
    "max_drawdown",
    "calmar",
    "hit_rate",
    "annual_turnover",
]


def _read_object(path: Path) -> dict | None:
    """Read a JSON object, or None when the artifact has not been produced."""
    if not path.exists():
        return None
    payload = json.loads(path.read_text())
    return payload if isinstance(payload, dict) else None


def _read_array(path: Path) -> list | None:
    """Read a JSON array, or None when the artifact has not been produced."""
    if not path.exists():
        return None
    payload = json.loads(path.read_text())
    return payload if isinstance(payload, list) else None


def _format_table(frame: pd.DataFrame, floatfmt: str = "{:.3f}") -> str:
    formatted = frame.copy()
    for column in formatted.columns:
        if pd.api.types.is_float_dtype(formatted[column]):
            formatted[column] = formatted[column].map(lambda v: floatfmt.format(v))
    header = "| " + " | ".join(str(c) for c in formatted.columns) + " |"
    divider = "| " + " | ".join("---" for _ in formatted.columns) + " |"
    body = [
        "| " + " | ".join(str(v) for v in row) + " |"
        for row in formatted.itertuples(index=False, name=None)
    ]
    return "\n".join([header, divider, *body])


def _rl_trace(config: Config) -> pd.DataFrame:
    path = RUN_DIR / config.run_name / "rl" / "metrics.jsonl"
    if not path.exists():
        return pd.DataFrame()
    records = [json.loads(line) for line in path.read_text().splitlines() if line.strip()]
    return pd.DataFrame([r for r in records if r.get("stage") == "rl"])


def render_report(config: Config, directory: Path | None = None) -> Path:
    """Write ``RESULTS.md`` from whatever artifacts are present."""
    directory = directory or REPORT_DIR
    directory.mkdir(parents=True, exist_ok=True)

    parts: list[str] = [
        "# GenDesk results",
        "",
        "Generated by `gendesk eval report`. Every number below comes from an artifact "
        "in `artifacts/reports/`; nothing here is transcribed by hand.",
        "",
        f"- Run: `{config.run_name}`",
        f"- Training window ends: `{config.backtest.train_end}`",
        f"- Validation window ends: `{config.backtest.valid_end}`",
        f"- Rebalance: every {config.backtest.rebalance_days} sessions, "
        f"{config.backtest.cost_bps} bp one-way costs",
        "",
    ]

    # -- backtest ------------------------------------------------------------
    backtest = _read_object(directory / "backtest_test.json")
    if backtest:
        summary = pd.DataFrame(backtest["summary"])
        columns = [c for c in HEADLINE_COLUMNS if c in summary.columns]
        parts += [
            "## Out-of-sample backtest",
            "",
            f"Window: **{backtest['start']} to {backtest['end']}**. Returns are the "
            "equal-weighted average across the six mandates; baselines that do not "
            "depend on a mandate are run once.",
            "",
            _format_table(summary[columns]),
            "",
        ]

        inference = backtest.get("inference", {})
        rows = []
        for name, payload in inference.items():
            test = payload["sharpe_test"]
            deflated = payload["deflated"]
            rows.append(
                {
                    "strategy": name,
                    "sharpe": test["estimate"],
                    "ci_low": test["ci_low"],
                    "ci_high": test["ci_high"],
                    "p_value": test["p_value"],
                    "deflated_sharpe_prob": deflated["dsr"],
                }
            )
        if rows:
            parts += [
                "### Inference",
                "",
                "Stationary block bootstrap (21-day blocks) for the confidence interval and "
                "p-value; deflated Sharpe probability accounts for the number of "
                "configurations tried.",
                "",
                _format_table(pd.DataFrame(rows)),
                "",
            ]

        comparisons = backtest.get("comparisons", {})
        if comparisons:
            rows = [
                {
                    "comparison": name.replace("_vs_", " vs "),
                    "sharpe_difference": payload["estimate"],
                    "ci_low": payload["ci_low"],
                    "ci_high": payload["ci_high"],
                    "p_value": payload["p_value"],
                }
                for name, payload in comparisons.items()
            ]
            parts += [
                "### Paired comparisons",
                "",
                "Both legs are resampled with the same block indices, which preserves their "
                "contemporaneous correlation and makes the difference test far tighter than "
                "comparing two independent intervals.",
                "",
                _format_table(pd.DataFrame(rows)),
                "",
            ]

        pbo = backtest.get("pbo", {})
        if pbo and pbo.get("pbo") == pbo.get("pbo"):  # not NaN
            parts += [
                f"Probability of backtest overfitting (CSCV, {pbo['n_splits']} splits over "
                f"{pbo['n_configs']} configurations): **{pbo['pbo']:.2%}**.",
                "",
            ]

    # -- ablations -----------------------------------------------------------
    ablations_path = directory / "ablations.csv"
    if ablations_path.exists():
        frame = pd.read_csv(ablations_path)
        parts += [
            "## Ablations",
            "",
            _format_table(
                frame[["family", "cell", "params_m", "loss", "mrr", "hit@5", "loss_vs_family_base"]]
            ),
            "",
        ]
        headline = summarise_headline(frame)
        if headline:
            parts += [
                "### Context enrichment versus capacity",
                "",
                f"- Full context versus rows-only prompt, at fixed capacity: "
                f"**{headline['context_loss_reduction']:.1%}** loss reduction, "
                f"**{headline['context_mrr_gain']:+.1%}** MRR.",
                f"- {headline['capacity_multiple']:.1f}x parameters at fixed full context: "
                f"**{headline['capacity_loss_reduction']:.1%}** loss reduction, "
                f"**{headline['capacity_mrr_gain']:+.1%}** MRR.",
                "",
            ]

    # -- latency -------------------------------------------------------------
    latency = _read_array(directory / "latency.json")
    if latency:
        parts += [
            "## Serving latency",
            "",
            "Hybrid row decoding autoregresses the first two slots of a row and fills the "
            "rest from a single forward pass, so the number of sequential model calls stops "
            "scaling with the number of slots.",
            "",
            _format_table(pd.DataFrame(latency)),
            "",
        ]

    # -- RL emergence --------------------------------------------------------
    trace = _rl_trace(config)
    if not trace.empty and "div_mean_correlation" in trace.columns:
        diversity = trace.dropna(subset=["div_mean_correlation"])
        if len(diversity) >= 2:
            first, last = diversity.iloc[0], diversity.iloc[-1]
            slopes = {
                column: float(
                    np.polyfit(
                        diversity["step"],
                        diversity[column],
                        1,
                    )[0]
                )
                for column in (
                    "div_mean_correlation",
                    "div_diversification_ratio",
                    "div_n_sectors",
                )
                if column in diversity.columns and diversity[column].notna().all()
            }
            # Lower correlation means more diversified; the others read the other way.
            score = sum(
                (1 if (s < 0 if c == "div_mean_correlation" else s > 0) else -1)
                for c, s in slopes.items()
            )
            verdict = (
                "**Replicated**: diversification rose over training."
                if score > 0
                else "**Did not replicate**: diversification fell over training."
                if score < 0
                else "**Inconclusive**: the measures disagree on direction."
            )
            parts += [
                "## Emergent diversification under RL",
                "",
                "GenPage reports that page diversity rises during RL without being "
                "optimised for. None of the quantities below appears in this reward, which "
                "is a risk-adjusted, benchmark-relative, turnover-penalised return.",
                "",
                verdict,
                "",
                _format_table(
                    pd.DataFrame(
                        [
                            {
                                "metric": "mean pairwise correlation",
                                "start": first["div_mean_correlation"],
                                "end": last["div_mean_correlation"],
                            },
                            {
                                "metric": "diversification ratio",
                                "start": first.get("div_diversification_ratio", float("nan")),
                                "end": last.get("div_diversification_ratio", float("nan")),
                            },
                            {
                                "metric": "distinct sectors per page",
                                "start": first.get("div_n_sectors", float("nan")),
                                "end": last.get("div_n_sectors", float("nan")),
                            },
                            {
                                # Smoothed over 20 steps: a single group's reward is far
                                # too noisy to quote as a start/end pair.
                                "metric": "mean group reward (20-step)",
                                "start": float(trace["mean_reward"].head(20).mean()),
                                "end": float(trace["mean_reward"].tail(20).mean()),
                            },
                        ]
                    )
                ),
                "",
            ]

    path = directory / "RESULTS.md"
    path.write_text("\n".join(parts))
    log.info("report_rendered", path=str(path))
    return path
